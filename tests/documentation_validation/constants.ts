export const RULE_EXAMPLES = [
	"# empty-error-handler",
	"",
	"## Bad",
	"```ts",
	"// File: cli.ts",
	"#!/usr/bin/env node",
	"try { work(); } catch {}",
	"```",
	"```py",
	"# File: cli.py",
	"if __name__ == '__main__':",
	"    try:",
	"        work()",
	"    except OSError:",
	"        pass",
	"```",
	"## Good",
	"```ts",
	"// File: cli.ts",
	"#!/usr/bin/env node",
	"(() => {",
	'\ttry { work(); } catch (error) { throw new Error("failed", { cause: error }); }',
	"})();",
	"```",
	"```py",
	"# File: cli.py",
	"if __name__ == '__main__':",
	"    try:",
	"        work()",
	"    except OSError as error:",
	'        raise RuntimeError("failed") from error',
	"```",
].join("\n");
export const TYPESCRIPT_RULE_EXAMPLES = RULE_EXAMPLES.replace(/```py\n[\s\S]*?```/gu, "");
export const PYTHON_RULE_EXAMPLES = RULE_EXAMPLES.replace(/```ts\n[\s\S]*?```/gu, "");

