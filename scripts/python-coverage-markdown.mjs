import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';

const project_root = process.cwd();
const json_file = resolve(project_root, 'coverage/python-coverage.json');
const markdown_file = resolve(project_root, 'coverage/python-uncovered.md');
const report = JSON.parse(readFileSync(json_file, 'utf8'));
const files = Object.entries(report.files)
	.map(([file, data]) => ({ file, data }))
	.filter(({ data }) => data.missing_lines.length > 0)
	.sort((left, right) => left.file.localeCompare(right.file));
const impact = ({ data }) => data.missing_lines.length + data.missing_branches.length;
const top_files = [...files]
	.sort((left, right) => impact(right) - impact(left) || right.data.missing_lines.length - left.data.missing_lines.length)
	.slice(0, 10);

const source_lines = (file) => readFileSync(resolve(project_root, file), 'utf8').split('\n');
const line_text = (lines, line) => lines[line - 1] ?? '';
const file_section = ({ file, data }) => {
	const lines = source_lines(file);
	const missing = data.missing_lines.map(line =>
		`- Line ${line}: ` + '`' + line_text(lines, line).trim() + '`'
	);
	return [`## \`${relative(project_root, file)}\``, '', ...missing, ''].join('\n');
};

mkdirSync(dirname(markdown_file), { recursive: true });
const summary = report.totals;
const header = [
	'# Python uncovered code',
	'',
	`Coverage: ${summary.percent_covered.toFixed(2)}% (${summary.covered_lines}/${summary.num_statements} statements).`,
	'',
	'Generated by `pnpm coverage`.',
	'',
];
const top_section = [
	'## Top 10 uncovered areas by impact',
	'',
	'Impact score = uncovered statements + uncovered branches.',
	'',
	'| Rank | File | Missing statements | Missing branches | Impact | Representative lines |',
	'| ---: | --- | ---: | ---: | ---: | --- |',
	...top_files.map(({ file, data }, index) => ['' ,
		index + 1,
		`\`${relative(project_root, file)}\``,
		data.missing_lines.length,
		data.missing_branches.length,
		impact({ data }),
		data.missing_lines.slice(0, 5).join(', '),
		''].join(' | ')),
	'',
];
const body = files.length === 0
	? ['No uncovered Python statements.', '']
	: files.flatMap(file => file_section(file).split('\n'));
writeFileSync(markdown_file, [...header, ...top_section, ...body].join('\n'));
